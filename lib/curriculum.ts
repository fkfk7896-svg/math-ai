export function findSection(sectionId: string): LessonSection {
  for (const group of CURRICULUM) {
    const section = group.sections.find((item) => item.id === sectionId);
    if (section) return section;
  }
  return CURRICULUM[0].sections[0];
}

export function findGroupTitle(sectionId: string): string {
  for (const group of CURRICULUM) {
    if (group.sections.some((item) => item.id === sectionId)) return group.title;
  }
  return CURRICULUM[0].title;
}
